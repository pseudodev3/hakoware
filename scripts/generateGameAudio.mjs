import { mkdirSync, writeFileSync } from 'node:fs';
import { Buffer } from 'node:buffer';
import { URL } from 'node:url';
import { cues } from '../src/lib/gameSoundCues.js';

// Reuse one activated media element, with a complete file for each cue. Native
// endings avoid iOS sprite seeks and wall-clock timers truncating later moves.
const rate = 22050, clips = {};
const directory = new URL('../src/assets/game-audio/', import.meta.url);
mkdirSync(directory, { recursive: true });
const writeWav = (name, samples) => {
  const wav = Buffer.alloc(44 + samples.length * 2);
  wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(rate, 24); wav.writeUInt32LE(rate * 2, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
  wav.write('data', 36); wav.writeUInt32LE(samples.length * 2, 40);
  samples.forEach((value, index) => wav.writeInt16LE(Math.round(Math.max(-1, Math.min(1, value)) * 32767), 44 + index * 2));
  writeFileSync(new URL(`${name}.wav`, directory), wav);
};
writeWav('activate', Array(Math.round(rate * .12)).fill(0));
for (const [kind, notes] of Object.entries(cues)) {
  const duration = Math.max(...notes.map(([, , delay, length]) => delay + length)) + .025;
  const segment = Array(Math.ceil(duration * rate)).fill(0);
  for (const [frequency, endFrequency, delay, length, volume, wave] of notes) {
    let phase = 0, filtered = 0;
    const alpha = 1 - Math.exp(-2 * Math.PI * 1600 / rate);
    for (let n = 0; n < Math.ceil(length * rate); n += 1) {
      const t = n / rate, pitch = frequency * (endFrequency / frequency) ** (t / length);
      phase += 2 * Math.PI * pitch / rate;
      const signal = wave === 'triangle' ? 2 / Math.PI * Math.asin(Math.sin(phase)) : Math.sin(phase);
      filtered += alpha * (signal - filtered);
      const envelope = t < .018 ? t / .018 : (.0001 / volume) ** ((t - .018) / (length - .018));
      // Phone speakers need a little more headroom, with peaks below 0.09.
      segment[Math.round(delay * rate) + n] += filtered * volume * envelope * 2.5;
    }
  }
  writeWav(kind, segment); clips[kind] = segment.length / rate;
}
const entries = Object.entries(clips).map(([kind, duration]) => `  ${JSON.stringify(kind)}: { src: new URL('../assets/game-audio/${kind}.wav', import.meta.url).href, duration: ${duration} }`);
writeFileSync(new URL('../src/lib/gameAudioClips.js', import.meta.url), `// Generated by scripts/generateGameAudio.mjs.\nexport const activationClip = new URL('../assets/game-audio/activate.wav', import.meta.url).href;\nexport const clips = {\n${entries.join(',\n')}\n};\n`);
